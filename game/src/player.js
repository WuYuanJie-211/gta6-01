import * as THREE from 'three';
import { PLAYER } from './config.js';
import { resolveBuildingCollision } from './city.js';
export function createPlayerMesh() {
  const group = new THREE.Group();
  const jacket = new THREE.MeshStandardMaterial({ color: 0x2e4053, roughness: 0.8 });
  const skin = new THREE.MeshStandardMaterial({ color: 0xe0ac69, roughness: 0.8 });
  const jeans = new THREE.MeshStandardMaterial({ color: 0x2c3e50, roughness: 0.9 });
  const torso = new THREE.Mesh(new THREE.BoxGeometry(0.7, 0.9, 0.4), jacket);
  torso.position.y = 1.15;
  torso.castShadow = true;
  group.add(torso);
  const head = new THREE.Mesh(new THREE.SphereGeometry(0.26, 14, 12), skin);
  head.position.y = 1.85;
  head.castShadow = true;
  group.add(head);
  const hair = new THREE.Mesh(new THREE.SphereGeometry(0.27, 12, 8, 0, Math.PI * 2, 0, Math.PI / 2), new THREE.MeshStandardMaterial({ color: 0x1a1a1a, roughness: 1 }));
  hair.position.y = 1.9;
  group.add(hair);
  const neck = new THREE.Mesh(new THREE.CylinderGeometry(0.09, 0.11, 0.18, 8), skin);
  neck.position.y = 1.68;
  group.add(neck);
  const legL = new THREE.Mesh(new THREE.BoxGeometry(0.26, 0.7, 0.3), jeans);
  legL.position.set(-0.18, 0.35, 0);
  const legR = new THREE.Mesh(new THREE.BoxGeometry(0.26, 0.7, 0.3), jeans);
  legR.position.set(0.18, 0.35, 0);
  group.add(legL, legR);
  const shoeMat = new THREE.MeshStandardMaterial({ color: 0x1a1a1a, roughness: 0.9 });
  const shoeL = new THREE.Mesh(new THREE.BoxGeometry(0.26, 0.12, 0.42), shoeMat);
  shoeL.position.set(-0.18, 0.06, 0.06);
  const shoeR = shoeL.clone();
  shoeR.position.x = 0.18;
  group.add(shoeL, shoeR);
  const armL = new THREE.Mesh(new THREE.BoxGeometry(0.2, 0.7, 0.22), jacket);
  armL.position.set(-0.48, 1.2, 0);
  const armR = new THREE.Mesh(new THREE.BoxGeometry(0.2, 0.7, 0.22), jacket);
  armR.position.set(0.48, 1.2, 0);
  group.add(armL, armR);
  const gunMat = new THREE.MeshStandardMaterial({ color: 0x1a1a1a, roughness: 0.4, metalness: 0.5 });
  const pistol = new THREE.Group();
  const pistolBody = new THREE.Mesh(new THREE.BoxGeometry(0.08, 0.14, 0.4), gunMat);
  const pistolGrip = new THREE.Mesh(new THREE.BoxGeometry(0.08, 0.18, 0.1), gunMat);
  pistolGrip.position.set(0, -0.12, -0.1);
  pistol.add(pistolBody, pistolGrip);
  const pistolBarrel = new THREE.Mesh(new THREE.BoxGeometry(0.06, 0.08, 0.28), gunMat);
  pistolBarrel.position.set(0, 0.03, 0.32);
  pistol.add(pistolBarrel);
  const pistolSight = new THREE.Mesh(new THREE.BoxGeometry(0.03, 0.06, 0.06), gunMat);
  pistolSight.position.set(0, 0.1, 0.15);
  pistol.add(pistolSight);
  pistol.position.set(0.48, 0.9, 0.35);
  pistol.visible = false;
  const rifle = new THREE.Group();
  const rifleBody = new THREE.Mesh(new THREE.BoxGeometry(0.09, 0.14, 0.9), gunMat);
  const rifleStock = new THREE.Mesh(new THREE.BoxGeometry(0.08, 0.16, 0.3), gunMat);
  rifleStock.position.set(0, -0.05, -0.45);
  const rifleMag = new THREE.Mesh(new THREE.BoxGeometry(0.07, 0.2, 0.12), gunMat);
  rifleMag.position.set(0, -0.14, 0.05);
  rifle.add(rifleBody, rifleStock, rifleMag);
  const rifleBarrel = new THREE.Mesh(new THREE.CylinderGeometry(0.03, 0.03, 0.5, 8), gunMat);
  rifleBarrel.rotation.x = Math.PI / 2;
  rifleBarrel.position.set(0, 0.02, 0.68);
  rifle.add(rifleBarrel);
  const rifleSight = new THREE.Mesh(new THREE.BoxGeometry(0.04, 0.1, 0.12), gunMat);
  rifleSight.position.set(0, 0.12, 0.3);
  rifle.add(rifleSight);
  rifle.position.set(0.48, 0.9, 0.4);
  rifle.visible = false;
  group.add(pistol, rifle);
  group.userData.legL = legL;
  group.userData.legR = legR;
  group.userData.armL = armL;
  group.userData.armR = armR;
  group.userData.pistol = pistol;
  group.userData.rifle = rifle;
  return group;
}
export function updatePlayerOnFoot(game, dt) {
  const player = game.player;
  const input = game.input;
  const drive = input.drive();
  const steer = input.steer();
  const speed = input.run() ? PLAYER.runSpeed : PLAYER.walkSpeed;
  const camAngle = game.cameraAngle;
  const moveAngle = camAngle + Math.PI - Math.atan2(steer, drive);
  const moving = drive !== 0 || steer !== 0;
  if (moving) {
    const step = speed * dt;
    player.pos.x += Math.sin(moveAngle) * step;
    player.pos.z += Math.cos(moveAngle) * step;
    resolveBuildingCollision(player.pos, PLAYER.radius, game.city.colliders);
    let diff = moveAngle - player.heading;
    while (diff > Math.PI) diff -= Math.PI * 2;
    while (diff < -Math.PI) diff += Math.PI * 2;
    player.heading += Math.max(-8 * dt, Math.min(8 * dt, diff));
  }
  player.mesh.position.copy(player.pos);
  player.mesh.rotation.y = player.heading;
  player.swingAmp = player.swingAmp ?? 0;
  player.swingAmp += ((moving ? 1 : 0) - player.swingAmp) * Math.min(1, dt * 6);
  const swing = Math.sin(game.time * 10) * 0.5 * player.swingAmp;
  player.mesh.userData.legL.rotation.x = swing;
  player.mesh.userData.legR.rotation.x = -swing;
  player.mesh.userData.armL.rotation.x = -swing;
  const punchT = Math.max(0, player.punchTimer);
  const armed = player.weapon && player.weapon !== 'fists';
  player.mesh.userData.armR.rotation.x = punchT > 0 ? -1.4 : armed ? -1.4 : 0;
  player.mesh.userData.pistol.visible = armed && player.weapon === 'pistol';
  player.mesh.userData.rifle.visible = armed && player.weapon === 'rifle';
  player.punchTimer = Math.max(0, player.punchTimer - dt);
  player.shootTimer = Math.max(0, (player.shootTimer || 0) - dt);
  player.reloadTimer = Math.max(0, (player.reloadTimer || 0) - dt);
}
